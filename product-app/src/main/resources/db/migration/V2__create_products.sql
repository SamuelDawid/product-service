CREATE TABLE products (
                          id               BIGINT GENERATED BY DEFAULT AS IDENTITY,
                          name             VARCHAR(255)   NOT NULL,
                          status           VARCHAR(20)    NOT NULL,
                          base_price_net   NUMERIC(19, 2) NOT NULL,
                          base_price_gross NUMERIC(19, 2) NOT NULL,
                          vat_rate         NUMERIC(5, 4)  NOT NULL,
                          configurable     BOOLEAN        NOT NULL,
                          category_id      BIGINT         NOT NULL,

                          CONSTRAINT pk_products PRIMARY KEY (id),
                          CONSTRAINT fk_product_category FOREIGN KEY (category_id) REFERENCES categories (id),
                          CONSTRAINT chk_product_name_not_blank CHECK (LENGTH(TRIM(name)) > 0),
                          CONSTRAINT chk_product_status CHECK (status IN ('DRAFT', 'ACTIVE', 'ARCHIVED')),
                          CONSTRAINT chk_product_base_price_net CHECK (base_price_net >= 0),
                          CONSTRAINT chk_product_base_price_gross CHECK (base_price_gross >= 0),
                          CONSTRAINT chk_product_vat_rate CHECK (vat_rate >= 0 AND vat_rate <= 1),
    -- ta sama tolerancja 1 grosza co w ProductPrice
                          CONSTRAINT chk_product_base_price_consistent
                              CHECK (ABS(base_price_gross - base_price_net * (1 + vat_rate)) <= 0.01)
);

CREATE INDEX idx_products_category_id ON products (category_id);