CREATE TABLE product_options (
                                 id         BIGINT GENERATED BY DEFAULT AS IDENTITY,
                                 name       VARCHAR(255) NOT NULL,
                                 required   BOOLEAN      NOT NULL,
                                 product_id BIGINT       NOT NULL,

                                 CONSTRAINT pk_product_options PRIMARY KEY (id),
                                 CONSTRAINT fk_product_option_product FOREIGN KEY (product_id) REFERENCES products (id),
    -- indeks tego UNIQUE zaczyna się od product_id, więc obsługuje też wyszukiwanie po FK
                                 CONSTRAINT uq_product_option_name UNIQUE (product_id, name),
                                 CONSTRAINT chk_product_option_name_not_blank CHECK (LENGTH(TRIM(name)) > 0)
);