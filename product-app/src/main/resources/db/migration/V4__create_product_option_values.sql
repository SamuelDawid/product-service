CREATE TABLE product_option_values (
                                       id                BIGINT GENERATED BY DEFAULT AS IDENTITY,
                                       name              VARCHAR(255)   NOT NULL,
                                       price_delta_net   NUMERIC(19, 2) NOT NULL,
                                       price_delta_gross NUMERIC(19, 2) NOT NULL,
                                       is_default        BOOLEAN        NOT NULL,
                                       option_id         BIGINT         NOT NULL,

                                       CONSTRAINT pk_product_option_values PRIMARY KEY (id),
                                       CONSTRAINT fk_product_option_value_option FOREIGN KEY (option_id) REFERENCES product_options (id),
    -- indeks tego UNIQUE zaczyna się od option_id, więc obsługuje też wyszukiwanie po FK
                                       CONSTRAINT uq_product_option_value_name UNIQUE (option_id, name),
                                       CONSTRAINT chk_product_option_value_name_not_blank CHECK (LENGTH(TRIM(name)) > 0),
    -- dopłata może być ujemna, ale netto i brutto muszą mieć ten sam znak
                                       CONSTRAINT chk_product_option_value_delta_sign CHECK (
                                           (price_delta_net >= 0 AND price_delta_gross >= price_delta_net)
                                               OR (price_delta_net <= 0 AND price_delta_gross <= price_delta_net)
                                           )
);