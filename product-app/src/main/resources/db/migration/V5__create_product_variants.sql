CREATE TABLE product_variants (
                                  id          BIGINT GENERATED BY DEFAULT AS IDENTITY,
                                  sku         VARCHAR(64)    NOT NULL,
                                  price_net   NUMERIC(19, 2) NOT NULL,
                                  price_gross NUMERIC(19, 2) NOT NULL,
                                  stock       INTEGER        NOT NULL,
                                  product_id  BIGINT         NOT NULL,

                                  CONSTRAINT pk_product_variants PRIMARY KEY (id),
                                  CONSTRAINT fk_product_variant_product FOREIGN KEY (product_id) REFERENCES products (id),
                                  CONSTRAINT uq_product_variant_sku UNIQUE (sku),
                                  CONSTRAINT chk_product_variant_sku_not_blank CHECK (LENGTH(TRIM(sku)) > 0),
                                  CONSTRAINT chk_product_variant_price_net CHECK (price_net >= 0),
                                  CONSTRAINT chk_product_variant_price_gross CHECK (price_gross >= price_net),
                                  CONSTRAINT chk_product_variant_stock CHECK (stock >= 0)
);

CREATE INDEX idx_product_variants_product_id ON product_variants (product_id);