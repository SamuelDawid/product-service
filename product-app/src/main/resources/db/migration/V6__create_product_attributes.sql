CREATE TABLE product_attributes (
                                    id              BIGINT GENERATED BY DEFAULT AS IDENTITY,
                                    name            VARCHAR(255) NOT NULL,
                                    attribute_value VARCHAR(255) NOT NULL,
                                    product_id      BIGINT       NOT NULL,

                                    CONSTRAINT pk_product_attributes PRIMARY KEY (id),
                                    CONSTRAINT fk_product_attribute_product FOREIGN KEY (product_id) REFERENCES products (id),
    -- indeks tego UNIQUE zaczyna się od product_id, więc obsługuje też wyszukiwanie po FK
                                    CONSTRAINT uq_product_attribute_name UNIQUE (product_id, name),
                                    CONSTRAINT chk_product_attribute_name_not_blank CHECK (LENGTH(TRIM(name)) > 0)
);